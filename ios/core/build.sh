#!/usr/bin/env bash
#
# Rebuild ios/Frameworks/LibXray.xcframework from pinned upstream sources.
#
# Mirrors android/core/build.sh. Before this existed the framework was a
# Fortiva fork nobody had the source for, six months stale, and outside the
# policy in CORE-MAINTENANCE.md. See issue #30.
#
# Usage:
#   ios/core/build.sh              # build at the pinned tag and verify
#   LIBXRAY_TAG=v26.8.1 ios/core/build.sh
#
# Requires: go, Xcode, and gomobile (installed automatically if missing).

set -euo pipefail

# Pin. Upstream at this tag builds Xray-core
# v1.260327.1-0.20260728075948-5ca6f4b7d4dc, which is the same commit
# android/core pins, so both platforms run one core version.
LIBXRAY_TAG="${LIBXRAY_TAG:-v26.7.28}"

# Only what a phone app needs. Upstream's own script also builds macos and
# maccatalyst, which is where the 516 MB of the previous framework came from.
# The simulator slice stays because the app has to link for simulator builds.
TARGETS="ios,iossimulator"
IOS_VERSION="15.0"

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DEST="$REPO_ROOT/ios/Frameworks/LibXray.xcframework"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/libxray-build.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

command -v go >/dev/null || { echo "go is required" >&2; exit 1; }
xcodebuild -version >/dev/null 2>&1 || { echo "Xcode is required" >&2; exit 1; }

export PATH="$PATH:$(go env GOPATH)/bin"
if ! command -v gomobile >/dev/null; then
  echo "Installing gomobile..."
  go install golang.org/x/mobile/cmd/gomobile@latest
fi

echo "Cloning XTLS/libXray at $LIBXRAY_TAG..."
git clone --depth 1 --branch "$LIBXRAY_TAG" https://github.com/XTLS/libXray.git "$WORK/libXray" 2>/dev/null

cd "$WORK/libXray"
echo "Xray-core pinned by this tag:"
grep -E 'xtls/xray-core' go.mod | sed 's/^/  /'

gomobile init
echo "Building for $TARGETS (this takes a few minutes)..."
gomobile bind -target "$TARGETS" -iosversion "$IOS_VERSION" -o LibXray.xcframework .

BIN="LibXray.xcframework/ios-arm64/LibXray.framework/LibXray"

# The whole point of rebuilding from source: no fork symbols, and the current
# single-dispatcher API rather than the fork's seven flat functions.
if nm -a "$BIN" 2>/dev/null | grep -qi fortiva; then
  echo "FAIL: fork symbols present in a build from upstream source" >&2
  exit 1
fi
if ! nm -a "$BIN" 2>/dev/null | grep -q 'LibXrayInvoke'; then
  echo "FAIL: LibXrayInvoke missing; ios/Runner/LibXrayCompat.swift needs it" >&2
  exit 1
fi

echo "Installing to $DEST"
rm -rf "$DEST"
cp -R LibXray.xcframework "$DEST"

cd "$REPO_ROOT"
{
  echo "# Generated by ios/core/build.sh - do not edit by hand."
  echo "#"
  echo "# libXray:    $LIBXRAY_TAG"
  echo "# Xray-core:  $(grep -oE 'v1\.[0-9a-z.-]+' "$WORK/libXray/go.mod" | head -1)"
  echo "# Built with: $(go version | awk '{print $3}'), $(xcodebuild -version | head -1 | tr ' ' '-'), gomobile bind -target $TARGETS -iosversion $IOS_VERSION"
  echo "#"
  echo "# Xray-core is the same commit android/core pins, so both platforms run one"
  echo "# auditable core version with one upstream to watch."
  echo
  for slice in ios-arm64 ios-arm64_x86_64-simulator; do
    printf '%s  %s\n' \
      "$(shasum -a 256 "$DEST/$slice/LibXray.framework/LibXray" | cut -d' ' -f1)" \
      "$slice/LibXray.framework/LibXray"
  done
} > ios/core/checksums.txt

echo
echo "Done. $(du -sh "$DEST" | cut -f1) in $DEST"
cat ios/core/checksums.txt
