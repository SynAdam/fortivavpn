#!/usr/bin/env bash
#
# Builds the Windows tunnel into dist/windows-<arch>/: fortiva-core.exe and
# what it needs next to it (wintun.dll, geoip.dat, geosite.dat, Wintun's
# licence), plus checksums.txt. Cross-compiles from any platform; nothing
# here needs Windows.
#
#   ./build.sh            amd64, which is every PC Fortiva expects
#   ./build.sh arm64      Windows on ARM
#
set -euo pipefail

cd "$(dirname "$0")"

log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

arch="${1:-amd64}"
case "$arch" in
  amd64|arm64) ;;
  *) die "unknown architecture $arch (amd64 or arm64)" ;;
esac

./stage.sh

if [[ -z "${GOTOOLCHAIN:-}" ]]; then
  export GOTOOLCHAIN="$(awk '$1=="toolchain"{print $2}' go.mod)"
fi

sha256() {
  if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

# The app's version, so "hello" can tell the app which core it is talking
# to and a mismatched pair shows up in diagnostics.
version=$(awk '$1=="version:"{print $2; exit}' ../../pubspec.yaml)
[[ -n "$version" ]] || die "no version in pubspec.yaml"

out="dist/windows-$arch"
rm -rf "$out"
mkdir -p "$out"

log "building fortiva-core $version for windows/$arch"
# -checklinkname=0: the TUN inbound reaches runtime.procyield through
# go:linkname, which Go 1.23+ refuses by default. Android's build passes it
# for the same reason.
GOOS=windows GOARCH="$arch" CGO_ENABLED=0 go build \
  -trimpath \
  -ldflags="-s -w -buildid= -checklinkname=0 -X main.version=$version" \
  -o "$out/fortiva-core.exe" \
  ./cmd/fortiva-core

cp .assets/wintun/"$arch"/wintun.dll "$out/wintun.dll"
cp .assets/wintun/LICENSE.txt "$out/wintun-LICENSE.txt"
cp .assets/geoip.dat .assets/geosite.dat "$out/"

# --- verify -----------------------------------------------------------------
# Each of these has a failure mode that would otherwise show up on a user's
# PC, at connect, rather than here.
log "verifying $out"
exe="$out/fortiva-core.exe"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

[[ "$(head -c 2 "$exe")" == "MZ" ]] || die "$exe is not a Windows executable"

# 1. Built from the patched core android/core stages, and nothing else.
go version -m "$exe" > "$work/buildinfo"
grep -q "GOOS=windows" "$work/buildinfo" || die "not built for Windows"
grep -q "GOARCH=$arch" "$work/buildinfo" || die "not built for $arch"
# The replacement is printed on the line after the module it replaces.
replaced=$(awk '$1=="dep" && $2=="github.com/xtls/xray-core" {getline; if ($1=="=>") print $2}' "$work/buildinfo")
[[ "$replaced" == "../../android/core/.src/xray-core" ]] || \
  die "xray-core does not come from android/core/.src (the patched source): ${replaced:-not replaced}"

# 2. What the doors and the tunnel need is compiled in. The autoselect
#    outbound comes from android/core/patches; a core without it refuses
#    every configuration with standby doors.
strings -a "$exe" > "$work/strings"
for feature in realitySettings xtls-rprx-vision xray.proxy.autoselect xray.proxy.tun \
               xray.transport.internet.finalmask.fragment; do
  grep -qF -- "$feature" "$work/strings" || die "core has no '$feature'"
done

# 3. Wintun is the archive stage.sh checked, for this architecture.
[[ "$(head -c 2 "$out/wintun.dll")" == "MZ" ]] || die "wintun.dll is not a Windows DLL"

# --- record -----------------------------------------------------------------
{
  echo "# Generated by windows/core/build.sh - do not edit by hand."
  echo "#"
  echo "# fortiva-core: $version (windows/$arch)"
  echo "# Xray-core:    $(awk '$1=="require" && $2=="github.com/xtls/xray-core" {print $3}
                            $1=="github.com/xtls/xray-core" && $2 ~ /^v/ {print $2}' go.mod | head -1)"
  for p in ../../android/core/patches/*.patch; do
    echo "# Patch:        $(basename "$p") sha256 $(sha256 "$p")"
  done
  echo "# Wintun:       $(cut -d' ' -f1 .assets/wintun/.stamp)"
  echo "# Built with:   $(go env GOVERSION)"
  echo
  for f in fortiva-core.exe wintun.dll geoip.dat geosite.dat; do
    echo "$(sha256 "$out/$f")  $f"
  done
} > "$out/checksums.txt"

log "built $out"
cat "$out/checksums.txt"
